// Builds the self-hosted RAGnarök icon font.
// Subsets node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff2 down
// to the glyphs listed in ICONS below, writes public/fonts/rag-icons.woff2
// (~10 kB) and generates src/rag-icons.css with matching .ri-* classes.
// Run after adding/removing icons:  npm run icons
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import subsetFont from 'subset-font';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BI = path.join(root, 'node_modules/bootstrap-icons/font');

// Icon names → css class suffix `.ri-<suffix>` (names must exist in
// bootstrap-icons/font/bootstrap-icons.json; unknown names abort the build).
const ICONS = {
  // navigation / app shell
  'chat-left-text': 'chat',
  'search': 'search',
  'files': 'docs',
  'funnel': 'filter',
  'database': 'sources',
  'people': 'admin',
  'sliders': 'settings',
  'activity': 'stats',
  'moon': 'moon',
  'sun': 'sun',
  'box-arrow-right': 'logout',
  'box-arrow-in-right': 'login',
  // document types
  'file-earmark-pdf': 'doc-pdf',
  'envelope': 'doc-email',
  'file-earmark-word': 'doc-word',
  'file-earmark-spreadsheet': 'doc-sheet',
  'file-earmark-ppt': 'doc-ppt',
  'file-earmark-text': 'doc-text',
  'markdown': 'doc-md',
  'file-earmark-code': 'doc-html',
  'code-slash': 'doc-code',
  'file-earmark-image': 'doc-image',
  'file-earmark': 'doc-unknown',
  // source kinds
  'folder': 'src-fs',
  'inbox': 'src-imap',
  'archive': 'src-paperless',
  'share': 'src-dav',
  'globe2': 'src-web',
  'rss': 'src-feed',
  'cloud': 'src-s3',
  'git': 'src-git',
  'calendar3': 'src-caldav',
  'mailbox': 'src-maildir',
  // actions / state
  'plus': 'plus',
  'send': 'send',
  'stop': 'stop',
  'signpost-2': 'steer',
  'play': 'play',
  'pause': 'pause',
  'gear': 'gear',
  'trash3': 'trash',
  'x-lg': 'close',
  'check-lg': 'check',
  'check-circle': 'ok',
  'x-circle': 'err',
  'slash-circle': 'denied',
  'exclamation-triangle': 'warn',
  'hourglass-split': 'busy',
  'download': 'download',
  'arrow-left': 'back',
  'chevron-left': 'prev',
  'chevron-right': 'next',
  'chevron-down': 'expand',
  'stopwatch': 'poll',
  'arrow-repeat': 'refresh',
  'arrow-clockwise': 'reindex',
  'link-45deg': 'link',
  'pencil': 'edit',
  'shield': 'role',
  'key': 'key',
  'plug': 'probe',
  // settings tabs / stats / misc
  'robot': 'llm',
  'layers': 'embed',
  'toggles': 'runtime',
  'journal-text': 'audit',
  'memory': 'ram',
  'cpu': 'cpu',
  'speedometer2': 'throughput',
  'lightning-charge': 'logo',
  'magic': 'magic',
};

const names = Object.keys(ICONS);
const meta = JSON.parse(await readFile(path.join(BI, 'bootstrap-icons.json'), 'utf8'));
const missing = names.filter(n => !(n in meta));
if (missing.length) {
  console.error(`unknown bootstrap-icons names: ${missing.join(', ')}`);
  process.exit(1);
}

const src = await readFile(path.join(BI, 'fonts/bootstrap-icons.woff2'));
const chars = names.map(n => String.fromCodePoint(meta[n])).join('');
const out = await subsetFont(src, chars, { targetFormat: 'woff2' });

await mkdir(path.join(root, 'public/fonts'), { recursive: true });
await writeFile(path.join(root, 'public/fonts/rag-icons.woff2'), out);
// MIT requires the license to ship with the font
await writeFile(
  path.join(root, 'public/fonts/LICENSE-bootstrap-icons'),
  await readFile(path.join(BI, '../LICENSE')),
);

const rules = names
  .map(n => `.ri-${ICONS[n]}::before { content: "\\${meta[n].toString(16)}"; }`)
  .join('\n');
const css = `/* GENERATED by scripts/build-icons.mjs — edit ICONS there, run \`npm run icons\`.
   Subset of Bootstrap Icons (MIT, https://icons.getbootstrap.com). */
@font-face {
  font-family: 'rag-icons';
  src: url('/fonts/rag-icons.woff2') format('woff2');
  font-display: block;
}
.ri {
  display: inline-block;
  font-family: 'rag-icons', sans-serif;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  line-height: 1;
  vertical-align: -0.125em;
  text-transform: none;
}
.ri::before { display: inline-block; }
${rules}
`;
await writeFile(path.join(root, 'src/rag-icons.css'), css);
console.log(`rag-icons.woff2: ${(out.length / 1024).toFixed(1)} kB, ${names.length} glyphs`);
